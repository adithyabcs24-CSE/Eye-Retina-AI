import React, { useState } from 'react';
import { apiClient } from '../../services/apiClient.js';
import styles from './GradCAMViewer.module.css';

export function GradCAMViewer({ file, targetId, previewUrl }) {
  const [enabled, setEnabled] = useState(false);
  const [loading, setLoading] = useState(false);
  const [status, setStatus] = useState(null); // 'loaded' | 'blocked' | null
  const [blockedReason, setBlockedReason] = useState(null);
  const [heatmapBase64, setHeatmapBase64] = useState(null);

  const handleToggle = async () => {
    if (enabled) {
      setEnabled(false);
      return;
    }

    setEnabled(true);
    if (!file || !targetId) return;

    setLoading(true);
    setStatus(null);

    try {
      const res = await apiClient.getGradCAM(file, targetId);
      if (res.status === 'not_available') {
        setStatus('blocked');
        setBlockedReason(res.message || 'Direct prediction model is in STUB state.');
      } else if (res.heatmap) {
        setStatus('loaded');
        setHeatmapBase64(res.heatmap);
      } else {
        setStatus('blocked');
        setBlockedReason('No activation map generated by inference service.');
      }
    } catch (err) {
      setStatus('blocked');
      setBlockedReason(err.message || 'Inference service failed to compute Grad-CAM.');
    } finally {
      setLoading(false);
    }
  };

  return (
    <div className={styles.container}>
      <div className={styles.headerRow}>
        <div className={styles.title}>
          <span>🔍</span> Explainability (Grad-CAM Attention Map)
        </div>
        <button
          type="button"
          onClick={handleToggle}
          className={`${styles.toggleBtn} ${enabled ? styles.toggleBtnActive : ''}`}
        >
          {enabled ? 'Disable Grad-CAM' : 'Enable Grad-CAM Overlay'}
        </button>
      </div>

      {/* Mandatory Caveat Requirement */}
      <div className={styles.caveatBanner}>
        <strong>Scientific Interpretation Caveat:</strong> Gradient-weighted Class Activation Mapping (Grad-CAM) shows where the model looked, not causal evidence of disease or systemic pathology.
      </div>

      {enabled && (
        <div>
          {loading && (
            <p style={{ color: 'var(--color-text-muted)', fontSize: '0.85rem' }}>
              Querying convolutional feature map activations from backend...
            </p>
          )}

          {status === 'blocked' && (
            <div className={styles.blockedNotice}>
              <strong>BLOCKED:</strong> {blockedReason}
            </div>
          )}

          {status === 'loaded' && heatmapBase64 && previewUrl && (
            <div className={styles.overlayCanvas}>
              <img
                src={previewUrl}
                alt="Original anterior ocular input"
                className={styles.overlayImg}
              />
              <img
                src={`data:image/png;base64,${heatmapBase64}`}
                alt="Grad-CAM convolutional activation heatmap"
                className={styles.heatmapImg}
              />
            </div>
          )}
        </div>
      )}
    </div>
  );
}

